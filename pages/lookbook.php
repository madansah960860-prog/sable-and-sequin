    <h2>What is not on this rail</h2>
    <p>Cocktail and festive, which are the two most common codes in American
    life, are in the decoder and are not photographed here. That is deliberate.
    Both are enormous categories that look like almost anything, and a single
    photograph of one cocktail dress would narrow them misleadingly. The decoder
    entry does more for you than a picture would.</p>
    <p>Also not here: anything for a black-tie wedding where you are in the
    wedding party, which is a different problem governed by somebody else's
    decisions, and menswear, which this site does not cover.</p>

    <h2>The three rules that survive every event</h2>
    <ol>
      <li><strong>Do not wear white to a wedding</strong> unless the couple has
      asked you to. This includes ivory, cream, champagne and blush that
      photographs white under a flash. It is the only rule in American occasion
      dressing that is close to absolute.</li>
      <li><strong>Hem to the shoe.</strong> A gown hemmed to the wrong heel
      height is the single most visible fitting error in a room, and it is a
      $35 to $70 fix. Bring the shoes to the fitting.</li>
      <li><strong>Sit down in it before you buy it.</strong> In the fitting room,
      on a chair, for a full minute. Half of occasion wear is worn seated, and a
      dress that pulls across the lap when you sit will be uncomfortable for four
      hours.</li>
    </ol>

    <h2>Getting two wears out of one dress</h2>
    <p>The arithmetic on occasion wear only works if a piece comes out more than
    once. Three things make that likelier: a color that is not memorable in a
    photograph, a silhouette that changes character with a different shoe and
    jacket, and a fabric that survives being cleaned.</p>
    <p>A black crepe column worn to a gala in March reappears at a December
    dinner with a different shoe and a shawl and nobody notices. A pale blue
    beaded gown with a distinctive neckline does not. Neither is a better dress;
    one of them is a better purchase.</p>
    <p>Full reasoning, and the point where renting wins instead, is in
    <a href="../guides/rental-versus-buying-the-math.php">rental versus
    buying</a>.</p>
