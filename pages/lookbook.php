    <h2 class="mt7">Read the fabric before the length</h2>
    <p>The most common error in American occasion dressing is treating length as
    the whole signal. It is not. A floor-length cotton sundress is not black tie
    and a midi in heavy silk crepe with an evening shoe very often is. Fabric
    carries formality; length carries it second.</p>
    <p>That is why the rows below lead with length and fabric together, and why
    the guide on
    <a href="../guides/black-tie-optional-decoded.php">black tie optional</a>
    spends most of its time on cloth rather than hemlines.</p>

