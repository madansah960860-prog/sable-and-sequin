      <h1>Renting, returning, and the nine-day problem</h1>
    </div>
    <p class="lede">Sable &amp; Sequin sells nothing and rents nothing. This
    page is about how American occasion-wear rental and returns actually work,
    and about the timing trap that catches almost everybody.</p>

    <div class="callout">
      <p><strong>We are a publication.</strong> Nothing here is for sale, no
      payment is taken through this site, and any policy governing something you
      bought or rented belongs to that retailer. This page explains how to read
      theirs.</p>
    </div>

    <h2>The nine-day problem</h2>
    <p>Almost everybody starts looking about nine days before the event. That is
    too late, and the reason is alterations rather than shipping. A gown that
    needs a hem and a take-in needs two to three weeks at a normal shop and
    costs a rush charge of 25 to 50 percent inside that. A beaded gown needs
    longer.</p>
    <p>Six weeks is the number to aim for if you are buying. Two weeks is fine
    if you are renting, because rental garments are not altered. That difference
    is, for a lot of people, the strongest argument for renting and it is almost
    never the one that gets made.</p>

    <h2>How U.S. occasion-wear rental works</h2>
