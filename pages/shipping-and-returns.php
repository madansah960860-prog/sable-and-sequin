    <p>Sales tax is added at checkout at the rate for your delivery address and
    varies by state, county and city, so no figure on this site is
    tax-inclusive. Several states also tax shipping charges themselves.</p>

    <h2>Your rights, plainly</h2>
    <p>There is no federal law in the United States requiring a retailer to
    accept a change-of-mind return. Return policies are contractual and the
    posted policy at the time of purchase governs. Faulty goods are different: a
    gown that arrives damaged, defective or materially not as described is a
    separate matter, and your card issuer's chargeback process and your state
    consumer protection office both exist for it.</p>
    <p>If a retailer misrepresents a material fact &mdash; the fabric, the
    color, whether a piece is final sale &mdash; that is a deceptive practice
    under the Federal Trade Commission Act and under most state analogues.
    Screenshot the listing before you contact them.</p>
