    <p>The backup size is the feature that makes rental work. A gown you cannot
    alter has to fit as it arrives, and a service that ships two sizes has
    removed most of the risk. One that does not is asking you to gamble.</p>

    <h2>What to check before you buy instead</h2>
    <dl class="mt5">
      <dt>Return window</dt>
      <dd>30 days is standard for U.S. occasion wear. Many formal-wear retailers run 14, and some sell gowns final sale. Find this before you fall in love.</dd>
      <dt>When the clock starts</dt>
      <dd>At purchase, at shipment or at delivery. A 14-day window starting at purchase, on a gown that ships in five days, is a nine-day window.</dd>
      <dt>Tags and condition</dt>
      <dd>Almost every occasion-wear return requires original tags attached and no alterations. Once a hem is cut, the dress is yours.</dd>
      <dt>Refund method</dt>
      <dd>Original payment, store credit or exchange only. Credit-only on a $400 gown is a materially worse deal and is usually stated in smaller type.</dd>
    </dl>

    <h2>Order two sizes, and do it early</h2>
    <p>Where returns are free, ordering two adjacent sizes is the rational move
    and it is what the retailer's pricing assumes. Occasion wear is the category
    where this matters most, because the sizing runs small and inconsistently and
    because you cannot judge a gown's fit from a product photograph.</p>
    <p>Do it six weeks out. Try both on with the actual underwear and the actual
    shoes, on a chair as well as standing, then send one back and take the other
    straight to the alterations shop.</p>

