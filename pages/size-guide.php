    </div>
    <p>The danger zone is 26 to 28 inches, which lands at the widest part of the
    calf on most people and flatters almost nobody. If a dress arrives at that
    length, it is a hem, not a return.</p>

    <h2>The hem decision</h2>
    <p>A floor-length gown is hemmed to half an inch off the floor <em>in the
    shoes you will wear</em>. Not in the shoes you own, not barefoot, not in the
    shoes you intend to buy later. Bring the actual shoes to the fitting or
    accept that the hem will be wrong.</p>
    <p>If you have not chosen shoes yet, choose the heel height first and tell
    the fitter the number. Three inches is the American default for evening. If
    you plan to change into flats at the reception, the gown is hemmed for the
    heel and you accept a puddle later, because it cannot be right for both.</p>

    <h2>Common gown fitting questions</h2>
    <details>
      <summary>Can a beaded gown be taken in?</summary>
      <p>Sometimes, and it costs two to four times what a plain fabric costs.
      Beading has to be cut away from the seam, the seam re-sewn, and the beads
      re-attached by hand across the join. Budget $120 to $260 rather than $50
      to $90, and allow three weeks rather than one. A heavily beaded gown
      should be bought closer to your measurements than a plain one.</p>
    </details>
    <details>
      <summary>My gown has a built-in bra and it does not fit</summary>
      <p>Built-in cups are placed for the fit model, not for you, and moving
      them is a standard $30 to $60 alteration that transforms the front of a
      dress. Ask for it by name: "reposition the cups." Removing them entirely
      and wearing your own bra is also fine and often better.</p>
    </details>
    <details>
      <summary>How much can a gown be let out?</summary>
      <p>Usually three quarters of an inch to two inches total, depending on the
      seam allowance, and less on anything beaded or with a boned bodice. Buy up
      and take in; that direction always works and the other frequently does
      not.</p>
    </details>
    <details>
      <summary>Do I need a strapless bra or shapewear?</summary>
      <p>Decide before the fitting, not after, because both change your
      measurements by up to an inch and a half. Wear whatever you intend to wear
      to the event to every fitting. This is the single most common cause of a
      gown that fitted in the shop and does not fit on the night.</p>
    </details>
    <details>
      <summary>How far ahead should I start?</summary>
      <p>Six weeks for a gown needing standard alterations, eight to ten if it
      is beaded or needs a bodice rebuilt, and twelve if it is being made to
      order. Two weeks is possible at a rush charge of 25 to 50 percent. The
      full timeline is in
      <a href="../guides/shapewear-and-alterations-for-occasion-wear.php">the
      alterations guide</a>.</p>
    </details>

