    <p>The W range is drafted with a different bust-to-waist ratio and a longer
    rise through the body rather than being the straight range scaled up, which
    is why a 16 and a 16W are not the same garment. If a house offers both, try
    both; the W cut usually fits better through the arm and the bodice even when
    the flat measurements look similar.</p>

