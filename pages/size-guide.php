      <p class="room__label">Sizing</p>
      <h1>Gown sizing, lengths and the hem you have not decided yet</h1>
    </div>
    <p class="lede">Occasion wear runs smaller than the rest of American
    clothing, is drafted from different blocks by different houses, and is
    almost always sold with the expectation that it will be altered.</p>

    <h2 class="mt7">Why gown sizing runs small</h2>
    <p>Two reasons, and neither is about you. Special-occasion and bridal
    manufacturers have historically used older sizing blocks than ready-to-wear,
    so the numbers never drifted downward the way everyday sizing did. And
    formal fabrics &mdash; crepe, satin, beaded mesh &mdash; have far less give
    than the jersey and stretch woven that modern day clothes are cut from.</p>
    <p>The practical result: expect to take one to two sizes larger in a gown
    than you take in a work dress from a mall brand, and expect that to feel
    unpleasant if nobody warned you. It is a fact about the pattern block, not a
    fact about your body, and every good fitter in America opens with that
    sentence.</p>

    <h2>Take these five before you shop</h2>
