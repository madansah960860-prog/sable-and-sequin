    <h2>Where the guidance comes from</h2>
    <p>Eleven years of fittings, mostly. When several thousand people bring you
    the same invitation wording and the same five worries, patterns emerge that
    do not appear in etiquette books, which tend to describe an idealized
    American formality that has not existed for forty years.</p>
    <p>Where a guide gives a price, it is what the work or the garment actually
    costs in a U.S. city at the review date printed on the page, excluding sales
    tax. Alterations prices come from a working shop in Nashville and are
    labeled as such; expect a coastal city to run 30 to 60 percent higher.</p>
    <p>Where a claim is regional, the guide names the region. Where it is a
    convention rather than a rule &mdash; which is nearly everything in this
    subject &mdash; it says so, because telling people there is one right answer
    when there are two is how this field became intimidating in the first
    place.</p>

    <h2>Review dates</h2>
    <p>Every guide carries the date it was last reviewed rather than only when
    it was written. Prices in this category move quickly: rental pricing and
    alteration labor have both changed noticeably in three years. A review
    means somebody read the page again and re-checked the numbers.</p>
    <p>Corrections go on the page, dated, saying what it used to say. We do not
    quietly edit and we do not delete a page to make an error disappear. The
    full policy is in the
    <a href="../policies/editorial-policy.php">Editorial Policy</a>.</p>

    <h2>What will not appear here</h2>
    <p>No invented testimonials, no fabricated reviews of a rental service, and
    no star ratings assembled from nothing. No sponsored guides. No affiliate
    link that decided a recommendation and no list ordered by commission rate.
    Where a page carries affiliate links, a disclosure sits above the first one,
    which is what the Federal Trade Commission requires and what we would do
    regardless.</p>
    <p>Also nothing about what body types should or should not wear. That
    framing is both useless and unkind, and the measurements on the
    <a href="../pages/size-guide.php">sizing page</a> do the job it pretends
    to do.</p>

    <h2>Suggest one</h2>
    <p>Three of these six came from reader mail. If there is an invitation
    wording nobody is explaining, send it.</p>
