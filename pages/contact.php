    <h2 class="mt7">Accessibility</h2>
    <p>Report a barrier to
    <a href="mailto:access@sableandsequin.com">access@sableandsequin.com</a> and
    say what you were trying to do. You do not need the technical term. We
    acknowledge within two business days and give an assessment with a target
    date within ten, which is set out in our
    <a href="../policies/accessibility-statement.php">Accessibility
    Statement</a>. This site is dark by design and we are aware that low-contrast
    dark interfaces are a common accessibility failure; every text and background
    pair here was computed rather than eyeballed, and if any of it is hard for
    you to read we want to hear about it specifically.</p>

