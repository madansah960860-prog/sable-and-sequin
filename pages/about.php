      <p class="room__label">About</p>
      <h1>Eleven years in a fitting room</h1>
    </div>
    <p class="lede">Sable &amp; Sequin is written from East Nashville by a
    former bridal and special-occasion fitter, with one contributor who hems
    gowns for a living. It exists because the anxiety around occasion dressing
    is an information problem and almost nobody treats it as one.</p>

    <div class="people mt7">
      <figure>
        <img src="../assets/images/people/editor-portrait.jpg"
             alt="Portrait of a woman in a black long-sleeved top with her arms folded, against a warm backdrop"
             width="460" height="575" loading="lazy" decoding="async">
        <figcaption>Rosalind Pruitt, founder and editor</figcaption>
      </figure>
      <div>
        <h2>Rosalind Pruitt</h2>
        <p>I spent eleven years in bridal and special occasion retail here in
        Nashville, seven of them as a fitter. That means I stood in a fitting
        room with several thousand people, most of them nine days out from an
        event, most of them holding an invitation they did not understand, and
        most of them quietly convinced that everybody else knew something they
        did not.</p>
        <p>They did not. The information is genuinely unavailable. An invitation
        says "black tie optional" and there is no page anywhere telling you what
        that looks like at a Saturday wedding in Nashville in October, which is
        a specific question with a specific answer.</p>
      </div>
    </div>

    <h2>What this site is for</h2>
    <p>Three things, in this order. Decoding the invitation, because that is the
    question people actually have. Telling you what it costs, because occasion
    wear has the worst cost per wear in all of clothing and nobody says so.
    And explaining alterations, because almost every gown needs them and the
    timeline is longer than anyone expects.</p>
    <p>The decoder on the home page is the spine of it: six American dress codes
    placed in order of formality, each with the same five answers. That format
    is fixed on purpose, so you can compare one code against the next rather
    than reading six essays.</p>

    <h2>What we say about money</h2>
    <p>A gown worn twice at $480 is $240 a wear. That is a terrible number and
    it is the real number, and a site about occasion dressing that never says it
    out loud is not being straight with you.</p>
    <p>So every price on this site is a band in U.S. dollars, before sales tax,
    which is added at checkout and varies by state, county and city. Every guide
    that recommends buying something says what the alternative costs. And there
    is a whole guide on
    <a href="../guides/rental-versus-buying-the-math.php">whether to rent
    instead</a>, which concludes that for a lot of people, a lot of the time, the
    answer is yes.</p>
    <p>We also do not pretend that spending more solves the problem. The single
    biggest improvement available to most people is $60 of alterations on a $180
    dress, and that is a much better use of money than $600 on something that
    fits off the rack the way off-the-rack fits, which is to say not well.</p>

    <h2>Regional honesty</h2>
    <p>Codes are conventions and conventions are local. Nashville and Charleston
    run more formal at the same stated code than Chicago or Minneapolis do. A
    Friday evening wedding runs a notch below a Saturday one. A church wedding
    runs above a barn wedding regardless of what the invitation says, and a
    daytime event in the South in August has a set of practical constraints that
    a formality scale does not capture at all.</p>
    <p>Where a piece of guidance is regional, this site says which region. Where
    it is genuinely universal &mdash; and only about three things are &mdash; it
    says that too.</p>

    <h2 id="photographs">About the photographs</h2>
    <p>The photographs here are licensed stock images. They are not our dresses,
    not garments we have fitted, and not the specific pieces being discussed. A
    caption never claims that a dress in a picture is the dress in the text.</p>
    <p>That matters on a site like this one, where a photograph could easily be
    read as a recommendation of a particular garment. It is not. The images show
    a silhouette, a length, a fabric behavior in low light, and nothing more.
    Every file, with its source URL, photographer and license, is listed in
    <code>assets/images/CREDITS.txt</code>, which ships with the site, and every
    image was checked for legible brand marks, identifiable individuals and
    minors before use.</p>

