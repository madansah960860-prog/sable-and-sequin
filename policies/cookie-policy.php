<h1>Cookie Policy</h1>
<p class="lede">Cookies are small text files a website asks your browser to keep. This page lists every category that can appear while you are reading sableandsequin.com, says who sets it, and shows how to refuse it.</p>
<p class="stamp">Effective September 1, 2026. Read alongside our <a href="privacy-policy.php">Privacy Policy</a>.</p>

<h2>What a cookie actually is</h2>
<p>A cookie is a short string of text stored by your browser and sent back to the server that set it on subsequent requests. A first-party cookie is set by the site you are looking at. A third-party cookie is set by another domain whose content is embedded in the page, which on this site means advertising. A session cookie disappears when you close the browser; a persistent cookie carries a stated expiry date. Related technologies do the same job by other means: local storage, web beacons, pixel tags, and device or advertising identifiers.</p>

<h2>Category one: strictly necessary</h2>
<p>Cookies without which a site cannot function: session state, load balancing, fraud prevention, and remembering a consent choice you already made. Sable & Sequin is a set of static pages. It has no login, no cart and no form that stores state between requests, so it sets no strictly necessary cookies of its own. If a consent banner is shown to you by our advertising partners, that banner will set one small cookie to remember your answer, because the alternative is asking you again on every page.</p>

<h2>Category two: analytics and performance</h2>
<p>These count visits, measure which pages are read, and record how long a page took to render. They are the category most sites use most heavily. Sable & Sequin runs no first-party analytics package. We do not embed Google Analytics, and no measurement script of ours runs in your browser, because there are no scripts on this site at all. What we know about traffic comes from server access logs, which are described in the <a href="privacy-policy.php">Privacy Policy</a> and which do not involve cookies. Advertising partners perform their own measurement, and that belongs in the next category.</p>

<h2>Category three: advertising and targeting</h2>
<p>This is the category that matters here. The reserved advertising slots on these pages are filled by Google and by vendors working with Google. Those companies may set cookies and read identifiers in order to choose which advertisement to show you, to cap how often you see the same one, to detect click fraud, and to measure whether an advertisement worked.</p>
<ul>
  <li><strong>DoubleClick / DART cookie.</strong> Set by Google to serve advertisements based on your visits to this site and to other sites on the internet. Opt out at the <a href="https://policies.google.com/technologies/ads" rel="nofollow noopener" target="_blank">Google advertising and content network privacy policy</a>.</li>
  <li><strong>Google advertising cookies and identifiers.</strong> Used for personalization, frequency capping and conversion measurement. Controlled at <a href="https://adssettings.google.com/" rel="nofollow noopener" target="_blank">Google Ads Settings</a>.</li>
  <li><strong>Partner network cookies.</strong> Other companies buying inventory through the same exchange may set their own. The Digital Advertising Alliance tool at <a href="https://optout.aboutads.info/" rel="nofollow noopener" target="_blank">optout.aboutads.info</a> covers many of them in one pass.</li>
</ul>
<p>We do not have a list of every company that may bid on a given impression, because the auction happens in the moment the page loads and we do not run it. Saying otherwise would be inventing certainty we do not have.</p>

<h2>Turning cookies off in your browser</h2>
<p>Every major browser lets you block third-party cookies, which is the setting that matters most here, and every one of them lets you delete what is already stored.</p>
<ul>
  <li><strong>Chrome.</strong> Settings, then Privacy and security, then Third-party cookies. Choose to block them. "Delete browsing data" clears what exists.</li>
  <li><strong>Safari, macOS and iOS.</strong> Prevent cross-site tracking is on by default. Settings, then Safari, then Clear History and Website Data to remove what is stored.</li>
  <li><strong>Firefox.</strong> Settings, then Privacy &amp; Security. Enhanced Tracking Protection set to Strict blocks cross-site cookies. Cookies and Site Data, then Clear Data.</li>
  <li><strong>Edge.</strong> Settings, then Cookies and site permissions, then Manage and delete cookies and site data. Tracking prevention offers Basic, Balanced and Strict.</li>
  <li><strong>Mobile.</strong> Both iOS and Android expose a per-app advertising identifier that you can reset or switch off in system settings; on iOS it is App Tracking Transparency, on Android it is Ads in Privacy settings.</li>
</ul>
<p>Blocking third-party cookies will not break this website. There is nothing here that depends on them. Advertisements will still appear and will simply be less relevant, which many readers consider an improvement.</p>

<h2>Global Privacy Control</h2>
<p>If your browser or extension sends a Global Privacy Control signal, we treat it as a valid opt-out of sale and sharing for the purposes of California law and of the other state statutes that recognize it. You do not need to email us as well.</p>

<h2>Do Not Track</h2>
<p>Some browsers send a Do Not Track header. There has never been an agreed standard for how a site should answer it, and most advertising systems ignore it. We do not rely on it and neither should you. The controls listed above and in <a href="privacy-policy.php#your-privacy-choices">Your Privacy Choices</a> are the ones that have an effect.</p>

<h2>Changes</h2>
<p>If the cookies on this site change in kind rather than in detail, this page is updated and the effective date changes with it.</p>
