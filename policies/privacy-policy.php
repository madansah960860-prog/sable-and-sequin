<h1>Privacy Policy</h1>
<p class="lede">Anyone who loads a page on sableandsequin.com leaves a short technical trail behind them, and the advertising that pays for the site adds a little more. This notice from Sable & Sequin describes that trail and what you can do about it.</p>
<p class="stamp">Effective September 1, 2026. This policy covers sableandsequin.com and every page beneath it.</p>

<h2>Who is responsible for this site</h2>
<p>Sable & Sequin is operated by Rosalind Pruitt, founder and editor, working from Nashville, Tennessee. The mailing address for written correspondence is at the foot of this page and on the contact page. For anything touching privacy, data or the removal of information, write to <a href="mailto:privacy@sableandsequin.com">privacy@sableandsequin.com</a>; the message reaches a person, not a ticket queue.</p>

<h2>What information we collect</h2>
<p>Because there is no login, no shopping cart and no member area, the categories below are short ones. In practice the information involved falls into four groups.</p>
<ul>
  <li><strong>Information you type and send us.</strong> If you email us or complete the inquiry form on the contact page, we receive whatever you chose to put in it: your name, your email address, and the content of your message. If you mention body measurements, a fit problem or a medical reason for a clothing question, that detail is used to answer you and nothing else.</li>
  <li><strong>Technical information collected automatically.</strong> Server log data, described in the next section.</li>
  <li><strong>Cookie and device information used for advertising.</strong> Set by third parties rather than by us, and described under advertising below.</li>
  <li><strong>Nothing else.</strong> We do not ask for dates of birth, we request no identity documents, there is no membership system on this website, and no payment is taken through it.</li>
</ul>

<h2>Log files</h2>
<p>Every request to this site produces a line in an access log held by our hosting provider. That line records the IP address of the connection, what was asked for, when, whether it succeeded, which browser asked, and which page linked there. These logs exist for operational reasons and are reviewed only when we are investigating an error or an unexplained spike in traffic.</p>

<h2>Cookies</h2>
<p>A cookie is a small text file that a website asks your browser to store and hand back on later visits. Sable & Sequin sets no cookies of its own for tracking. Cookies that do appear while you read these pages are placed by the third-party services described below. A fuller account, including how to switch cookies off in each major browser, is in our <a href="cookie-policy.php">Cookie Policy</a>.</p>

<h2>Third-party vendors and advertising</h2>
<p>This site carries display advertising, and the slots reserved in the layout are filled by advertising technology operated by other companies. Those companies may use cookies, web beacons, device identifiers and similar technologies to select and measure the advertisements shown to you.</p>
<p>This site is supported by display advertising served by Google. Google, as a third-party vendor, uses cookies to serve ads here, and Google's use of the DoubleClick DART cookie enables it to serve advertisements to users based on their visits to this site and other sites on the internet. Opting out of the DART cookie is done through Google's advertising and content network privacy policy.</p>
<p>Third-party ad servers and ad networks use technology in the advertisements and links that appear on sableandsequin.com and send a signal directly to your browser. When this happens they automatically receive your IP address. These technologies measure the effectiveness of advertising campaigns and personalize the advertising content that you see. Sable & Sequin has no access to, and no control over, cookies used by third-party advertisers.</p>
<p>Consult the privacy policies of those third-party ad servers for detail on their practices and for instructions about opting out. The policy you are reading does not apply to, and we cannot control the activities of, other advertisers or other websites.</p>

<h2 id="your-privacy-choices">Your Privacy Choices</h2>
<p>This is the section the "Your Privacy Choices" link in our footer points at. Everything here works without contacting us and takes about two minutes.</p>
<ul>
  <li>Visit <a href="https://adssettings.google.com/" rel="nofollow noopener" target="_blank">Google Ads Settings</a> to turn off ad personalization on Google services and on sites that use Google advertising, including this one.</li>
  <li>Visit <a href="https://optout.aboutads.info/" rel="nofollow noopener" target="_blank">optout.aboutads.info</a>, run by the Digital Advertising Alliance, to opt out of interest-based advertising from many companies at once.</li>
  <li>Visit the <a href="https://policies.google.com/technologies/ads" rel="nofollow noopener" target="_blank">Google advertising and content network privacy policy</a> for the DoubleClick DART cookie opt-out described above.</li>
  <li>Turn on Global Privacy Control in a browser or extension that supports it. We treat a GPC signal as a valid opt-out of sale and sharing under California law.</li>
  <li>Switch third-party cookies off in your browser, or install a reputable content blocker. Advertising still appears; it is simply chosen without reference to your browsing history.</li>
  <li>Email <a href="mailto:privacy@sableandsequin.com">privacy@sableandsequin.com</a> with "Do Not Sell or Share" in the subject line and we will record the request against the information we hold.</li>
</ul>
<p>Opting out stops personalization. It does not stop advertisements and it does not reduce how many you see.</p>

<h2>California residents: CCPA and CPRA rights</h2>
<p>If you live in California, the California Consumer Privacy Act as amended by the California Privacy Rights Act gives you specific rights over personal information relating to you.</p>
<ul>
  <li><strong>The right to know.</strong> You may ask what categories of personal information we have collected, the sources, the business purpose, and the categories of third parties involved.</li>
  <li><strong>The right to delete.</strong> You may ask us to delete personal information we have collected from you, subject to the narrow exceptions the statute allows.</li>
  <li><strong>The right to correct.</strong> You may ask us to fix inaccurate personal information.</li>
  <li><strong>The right to opt out of sale or sharing.</strong> Exercised through the choices listed above.</li>
  <li><strong>The right to limit use of sensitive personal information.</strong> We do not collect sensitive personal information as the statute defines it.</li>
  <li><strong>The right to non-discrimination.</strong> Exercising any of these rights changes nothing about what you can read here or how the site behaves for you.</li>
</ul>
<p>Sable & Sequin does not sell personal information for money. Advertising technology we do not control may nonetheless constitute "sharing" for cross-context behavioral advertising under California law, which is why the opt-out links above are the effective remedy. In the twelve months preceding the date at the top of this page, the categories of personal information collected were identifiers (IP address, email address if you wrote to us) and internet activity information (pages requested, referrer). Requests may be sent to <a href="mailto:privacy@sableandsequin.com">privacy@sableandsequin.com</a> with "California privacy request" in the subject line; we verify by replying to the address the request came from and respond within forty-five days. An authorized agent may act for you with written permission.</p>

<h2>Virginia, Colorado, Connecticut, Utah and Texas residents</h2>
<p>Residents of Virginia under the Virginia Consumer Data Protection Act, Colorado under the Colorado Privacy Act, Connecticut under the Connecticut Data Privacy Act, Utah under the Utah Consumer Privacy Act and Texas under the Texas Data Privacy and Security Act have broadly similar rights: to confirm whether we process personal data about you and to access it, to correct inaccuracies, to delete it, to obtain a portable copy, and to opt out of targeted advertising and of profiling that produces legal or similarly significant effects. We do not engage in such profiling and we do not process personal data for sale as those statutes define it. Use the same email address and the same opt-out links. Virginia, Colorado, Connecticut and Texas residents who are dissatisfied with our answer may appeal by replying to our response with the word "appeal" in the subject line; we will answer an appeal within sixty days and, if we deny it, tell you how to contact your state attorney general.</p>

<h2>Children's privacy</h2>
<p>Sable & Sequin does not knowingly collect personal information from children under the age of 13, and this website is not directed to children. Under the Children's Online Privacy Protection Act, if you believe a child has provided personal information through this site, contact <a href="mailto:privacy@sableandsequin.com">privacy@sableandsequin.com</a> and we will make our best efforts to remove it promptly. Nothing on this site is directed at children. The sizing, the shopping advice and the garment notes are written for adults buying their own clothes, and no part of the site asks a minor for information.</p>

<h2>Email and CAN-SPAM</h2>
<p>If you ask to hear from us, we tell you at the point of signup what you are getting and how often, every message names Sable & Sequin and carries our physical mailing address, and every message contains a working one-click unsubscribe that we honor immediately. We do not rent, sell or trade email addresses, and we do not use misleading subject lines. That is the Controlling the Assault of Non-Solicited Pornography and Marketing Act in practice.</p>

<h2>Visitors from outside the United States</h2>
<p>This site is operated from the United States and written for readers here. If you visit from the United Kingdom, the European Economic Area or elsewhere, your information is processed in the United States under the practices described above. Readers in those jurisdictions may ask for access, correction, erasure, restriction, portability, or to object to processing, using the same email address.</p>

<h2>Security and retention</h2>
<p>The site is served over HTTPS. Email correspondence is kept only as long as the exchange is useful and is then deleted. Server logs are retained for a limited operational period by our hosting provider. No system is perfectly secure and we will not pretend otherwise; what we can honestly say is that there is very little here to lose, because we hold very little.</p>

<h2>Changes to this policy</h2>
<p>If this policy changes materially, the effective date at the top changes with it and the change is described in the first paragraph of this section for at least thirty days. We do not make quiet edits to documents like this one.</p>

