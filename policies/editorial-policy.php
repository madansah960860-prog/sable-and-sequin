<h1>Editorial Policy</h1>
<p class="lede">A reader is entitled to know who wrote something, how they know it, when it was last checked, and what happens when it turns out to be wrong. This page answers all four for sableandsequin.com.</p>
<p class="stamp">Effective September 1, 2026.</p>

<h2>Who writes this site</h2>
<p>Sable & Sequin is written and edited by Rosalind Pruitt, founder and editor, in Nashville, Tennessee. Where an outside contributor writes something, they are named on the page with a line about why they are worth listening to on that subject. We do not publish anonymous filler, we do not buy articles from content mills, and we do not accept guest posts submitted to get a link.</p>
<p>No page on this site is generated and published without a human writing and checking it. If that ever changes for any part of the site, it will be disclosed on the page itself, not in a footnote here.</p>

<h2>How we research</h2>
<ul>
  <li><strong>We wear the clothes.</strong> Fit notes, wear reports and care advice come from garments we own or have worn, for the period stated. Where we are describing a category rather than a specific piece, the page says so.</li>
  <li><strong>Measurements are measured.</strong> Garment dimensions are taken flat with a tape, in inches, and the method is stated so you can repeat it on something in your own closet.</li>
  <li><strong>Brand claims are checked against the product.</strong> If a maker says a fabric is 14 oz denim or a boot is Goodyear welted, we look for the evidence before repeating it, and we say when we could not confirm it.</li>
  <li><strong>Prices are checked on the day of review</strong> at the retailer's own site, excluding tax, and the review date is printed on the page.</li>
  <li><strong>We keep the sources.</strong> Where a claim comes from a document, we link the document rather than a summary of it, so you can check our reading of it.</li>
</ul>

<h2>Review and dating</h2>
<p>Pages carry the date they were last reviewed, not just the date they were written. A review means somebody read the page again with fresh eyes, checked the things that go stale, and either confirmed or changed them. Pages with time-sensitive numbers are prioritized over reflective ones. A date on this site is a claim about work that was done, which is why we do not bump it automatically.</p>
<p>When a page is substantially rewritten rather than touched up, the change is noted at the foot of the page. We do not quietly replace a recommendation and leave the original date in place.</p>

<h2>Corrections</h2>
<p>We correct errors of fact quickly and visibly. A typo is fixed silently. A wrong number, a wrong name, a wrong distance, a wrong price band or a wrong claim gets a dated correction note on the page saying what it used to say and what it says now. We do not delete a page to make a mistake disappear, and we do not edit a paragraph out from under a reader who is arguing with it.</p>
<p>To request a correction, write to <a href="mailto:editor@sableandsequin.com">editor@sableandsequin.com</a> with the page URL and the specific sentence. You will get a reply from a person. If you are right, we will say so on the page and thank you there. If we think you are wrong, you will get the reasoning rather than silence.</p>

<h2>Sources, links and attribution</h2>
<p>We link generously and we link to the primary source where one exists. Quotations are short, attributed and linked. We do not republish another site's work, paraphrase an article closely enough to be a copy, or use another publication's research without saying whose it is.</p>

<h2>What advertising is not allowed to touch</h2>
<p>The advertising on this site is programmatic. Slots are filled automatically in the moment the page loads, by systems we do not operate. There is no advertiser relationship to compromise because there is no advertiser we deal with. In practice that means:</p>
<ul>
  <li>No advertiser sees a draft, requests a change, or has a page taken down.</li>
  <li>No topic is chosen, avoided or ordered because of what it does to revenue.</li>
  <li>An affiliate commission never determines a recommendation or the order of a list. Where we recommend against buying something, the affiliate link comes out, not the criticism.</li>
  <li>Advertisements are visually separated from editorial, sit in slots labeled "Advertisement", and never imitate the site's own typography.</li>
</ul>
<p>The full account of how the site is funded is in the <a href="affiliate-and-advertising-disclosure.php">Affiliate and Advertising Disclosure</a>.</p>

<h2>Testimonials and reviews</h2>
<p>We publish no fabricated testimonials, no invented user reviews and no aggregate ratings assembled from nowhere. Where illustrative copy appears in a layout it is labeled as illustrative in plain sight. The Federal Trade Commission's rule on consumer reviews and testimonials is enforced with civil penalties, and beyond that, a made-up quote is simply a lie to a reader.</p>

<h2>Independence and conflicts</h2>
<p>If we have a relationship with an organization we write about &mdash; a family connection, a paid engagement, a free stay, a sample we kept &mdash; it is disclosed on the page. Receiving something free creates no obligation to write about it and no obligation to be kind about it.</p>

<h2>Reader mail</h2>
<p>Corrections, disagreements and better information are welcome and are read by the person whose name is on the page.</p>
