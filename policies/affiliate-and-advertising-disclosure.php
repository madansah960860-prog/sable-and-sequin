<h1>Affiliate and Advertising Disclosure</h1>
<p class="lede">Sable & Sequin earns its income from the advertisements that appear alongside the writing and from a small number of affiliate links. The Federal Trade Commission requires that to be disclosed clearly and conspicuously. Here it is.</p>
<p class="stamp">Effective September 1, 2026. Published in compliance with the Federal Trade Commission's Guides Concerning the Use of Endorsements and Testimonials in Advertising, 16 CFR Part 255.</p>

<h2>The short version</h2>
<p class="callout"><strong>We earn a commission if you buy through some of the links on this site, and we are paid for the advertisements you see. It costs you nothing extra, and it does not change what we recommend.</strong></p>
<p>That sentence, or one like it, also appears at the top of any page that carries an affiliate link, above the first link rather than buried at the bottom. The FTC requires a disclosure that is clear and conspicuous, which means a reader should meet it before the link, not after.</p>

<h2>Display advertising</h2>
<p>sableandsequin.com is funded principally by display advertising. The reserved slots in the page layout, each labeled "Advertisement", are filled by third-party advertising technology, principally Google's advertising network. We are paid on the basis of impressions and clicks. The specific advertisement you see is chosen automatically, in the fraction of a second while the page loads, by systems we neither operate nor inspect.</p>
<p>Two consequences are worth stating plainly. First, we do not know in advance what will appear next to an article, and two readers on the same page will often see different advertisements. Second, an advertisement on this site is not a recommendation from us. Apply to it the same skepticism you would apply to an advertisement anywhere else.</p>
<p>The slots have fixed reserved dimensions in the stylesheet so the page does not jump while an advertisement loads. Nothing on this site moves under your finger as you go to tap it.</p>

<h2>Affiliate links</h2>
<p>Some outbound links to retailers are affiliate links. If you follow one and buy something, the retailer may pay us a small commission. The price you pay is identical to the price you would pay arriving there any other way, and the commission comes out of the retailer's margin, not your wallet.</p>
<p>Sable & Sequin participates in retailer and network affiliate programs of the kind that require this notice: as an Amazon Associate we earn from qualifying purchases. Other programs are operated directly by individual retailers or through affiliate networks.</p>
<p>Our rules for affiliate links are short and we keep to them:</p>
<ul>
  <li>We link only to something we have actually worn or handled, or to a category page where the choice is genuinely yours to make.</li>
  <li>We link to the thing we recommend, not to whichever program pays best.</li>
  <li>We do not stuff an article with links to manufacture opportunities.</li>
  <li>A commission never determines whether a piece gets written, what it concludes, or the order of a list.</li>
  <li>Where we recommend against something, the link comes out and the criticism stays.</li>
  <li>Every page with affiliate links says so, on the page, above the links.</li>
</ul>

<h2>Sponsored content</h2>
<p>We do not currently publish sponsored articles, paid reviews, paid guest posts or paid link placements. If that changes, any such item will be labeled at the top of the page, before the content, in the same typeface and size as the rest of the page, using the words "Paid content" or "Sponsored". It will never be dressed up as ordinary editorial. We do not sell links in existing articles, and requests to buy one are deleted unanswered.</p>

<h2>Gifts, samples and hosted stays</h2>
<p>If a brand sends something free of charge, that fact is stated in any piece that mentions it, along with whether we kept it. Receiving an item creates no obligation to write about it and no obligation to be kind about it. Items we do not rate do not get a favorable write-up, and most of the time they do not get written about at all.</p>

<h2>No fabricated endorsements</h2>
<p>We publish no invented testimonials, no fake reviews, no purchased ratings and no quotes from customers who do not exist. Under the FTC's rule on consumer reviews and testimonials this is enforceable with civil penalties, and it is also the difference between a publication and a billboard.</p>

<h2>What advertising does not influence</h2>
<ul>
  <li>Which topics are covered, and in what order.</li>
  <li>What a piece concludes, including when the conclusion is unhelpful to a potential advertiser.</li>
  <li>Whether a correction is published.</li>
  <li>Which links appear inside the editorial text.</li>
  <li>The ranking of anything listed on this site.</li>
</ul>
<p>Advertisers have no editorial control here. The separation is structural rather than a matter of goodwill: the advertising is programmatic, so there is no relationship to compromise in the first place.</p>

<h2>Your choices</h2>
<p>You can stop advertising being personalized to you without leaving the site. The controls are listed in full under <a href="privacy-policy.php#your-privacy-choices">Your Privacy Choices</a>, and browser-level cookie controls are in our <a href="cookie-policy.php">Cookie Policy</a>. If you use a content blocker we are not going to nag you about it. There is no wall, no interstitial, and no counting of how many pages you have read.</p>

<h2>Questions</h2>
<p>If you want to know whether a specific page carries an affiliate link, or how a particular arrangement works, ask and you will get a straight answer.</p>
