<p>Everything on this site is styling opinion and buying research, written by people who care about clothes. It is not professional advice of any kind. It is not a personal styling consultation, it is not legal or financial advice, and where a garment touches on health, such as compression, footwear or fit during pregnancy, it is not medical advice. If you need advice specific to your body, your budget or your circumstances, see a professional who can look at you.</p>

<h2>Sizing varies by brand, and by production run</h2>
<p>American sizing is not standardized. A women's size 8 in one label is a 6 in another and a 10 in a third. Men's waist measurements on the tag routinely differ from the actual garment by an inch or more, a practice known as vanity sizing. Shoe lasts differ, so a D width in one boot is not a D width in another. Denim shrinks, wool relaxes, and knitwear grows in the shoulders.</p>
<p>The measurements and fit notes on this site are stated in inches and describe specific garments we measured or wore, in the condition described. They are a starting point for comparison, not a guarantee that a particular size will fit you. Check the maker's own size chart, measure a garment you already own flat on a table, and where a retailer offers free returns, order two sizes and send one back.</p>

<h2>Prices, availability and links</h2>
<p>Prices are quoted in U.S. dollars, were accurate when the page was last reviewed, and exclude sales tax, which is added at checkout and varies by state, county and city. Nothing here is a tax-inclusive price and nothing here is an offer to sell. Prices change, items sell out, colorways are discontinued, and a link that worked when the page was written can lead somewhere unhelpful later. Where a page carries affiliate links, that is disclosed on the page above the first link and in our <a href="affiliate-and-advertising-disclosure.php">Affiliate and Advertising Disclosure</a>.</p>

<h2>Secondhand, vintage and resale</h2>
<p>Where we discuss the secondhand market, price ranges reflect what we observed, not what you will be offered or what you will realize. Resale values fall as often as they rise. Authentication guidance describes indicators, not proof: counterfeiters adapt, and the only authoritative word on whether an item is genuine comes from the brand or a professional authenticator. Treat anything we say about value as description rather than as an investment recommendation, because it is not one.</p>

<h2>Care instructions</h2>
<p>Washing, drying, pressing, waxing, conditioning and repair advice on this site is general and reflects our own experience with our own garments. Fabrics, finishes, dyes and constructions differ, and a method that is safe on one piece will ruin another. The care label on your garment outranks anything written here. Test on a hidden area first, and for anything valuable or unusual, use a professional cleaner. We are not responsible for damage to a garment you treated using information from this site.</p>

