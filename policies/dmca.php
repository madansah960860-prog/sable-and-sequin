<h1>DMCA and Copyright Policy</h1>
<p class="lede">Sable & Sequin respects the copyright of others and expects the same in return. This page explains how to tell us that something here infringes your work, and how to respond if your own material was removed by mistake.</p>
<p class="stamp">Effective September 1, 2026. This policy implements the Digital Millennium Copyright Act, 17 U.S.C. &sect;512.</p>

<h2>Our position</h2>
<p>Everything published on sableandsequin.com is either written by us, licensed, or used with permission. Photographs come from stock libraries under licenses that permit commercial use, and every image file shipped with this site is listed with its source and license in the CREDITS file inside the images folder. Original vector artwork is drawn by hand. We do not scrape, spin or republish other people's writing.</p>
<p>Mistakes are still possible. A contributor may supply something they had no right to supply. A license may be misread. If that has happened, we want the notice, we will act on it quickly, and we would rather hear from you directly than from a lawyer.</p>

<h2>Designated agent</h2>
<p>Notices under &sect;512(c)(3) should be sent to our designated agent:</p>
<p class="addr">Rosalind Pruitt, Designated Copyright Agent<br>Sable & Sequin<br>Sable &amp; Sequin<br>1112 Woodland Street, Suite 201<br>Nashville, TN 37206<br>Email <a href="mailto:dmca@sableandsequin.com">dmca@sableandsequin.com</a><br>Phone (615) 555-0173</p>
<p>Email is faster and is the preferred channel. Please put "DMCA notice" in the subject line.</p>

<h2>What a valid notice must contain</h2>
<p>To be effective under 17 U.S.C. &sect;512(c)(3)(A), your written notice must include substantially all of the following. A notice missing these elements may not be legally effective, and we may not be able to act on it.</p>
<ol>
  <li>A physical or electronic signature of a person authorized to act on behalf of the owner of the exclusive right that is allegedly infringed.</li>
  <li>Identification of the copyrighted work claimed to have been infringed, or, if multiple works at a single site are covered by a single notification, a representative list of those works.</li>
  <li>Identification of the material that is claimed to be infringing and that is to be removed, with information reasonably sufficient to let us locate it &mdash; in practice, the full URL of the page and a description of the specific paragraph, image or file.</li>
  <li>Information reasonably sufficient to permit us to contact you: an address, a telephone number, and, if available, an email address.</li>
  <li>A statement that you have a good faith belief that use of the material in the manner complained of is not authorized by the copyright owner, its agent, or the law.</li>
  <li>A statement that the information in the notification is accurate, and under penalty of perjury, that you are authorized to act on behalf of the owner of an exclusive right that is allegedly infringed.</li>
</ol>

<h2>What happens when we receive a notice</h2>
<p>We acknowledge receipt, usually within two business days. We review the claim against our own records of where the material came from. Where the claim is well founded, or where we cannot quickly establish that it is not, we remove or disable access to the material expeditiously and tell you that we have. We then notify whoever supplied the material, give them a copy of the notice, and explain that they may file a counter-notification.</p>
<p>We keep a record of notices received and of what we did about them. Under &sect;512(i) we terminate, in appropriate circumstances, the access of anyone who is a repeat infringer.</p>

<h2>Counter-notification</h2>
<p>If your material was removed and you believe that removal was the result of mistake or misidentification, you may send a counter-notification to the same agent. Under &sect;512(g)(3) it must include:</p>
<ol>
  <li>Your physical or electronic signature.</li>
  <li>Identification of the material that was removed and the location at which it appeared before removal.</li>
  <li>A statement under penalty of perjury that you have a good faith belief the material was removed or disabled as a result of mistake or misidentification.</li>
  <li>Your name, address and telephone number, and a statement that you consent to the jurisdiction of the Federal District Court for the judicial district in which your address is located, or, if your address is outside the United States, for any judicial district in which we may be found, and that you will accept service of process from the person who filed the original notice or their agent.</li>
</ol>
<p>On receiving a valid counter-notification we forward it to the original complainant. If they do not notify us within ten business days that they have filed an action seeking a court order to restrain the allegedly infringing activity, we may restore the material in not less than ten and not more than fourteen business days after receiving the counter-notification.</p>

<h2>A warning about false claims</h2>
<p>Section 512(f) provides that any person who knowingly materially misrepresents that material is infringing, or that material was removed by mistake, is liable for damages, including costs and attorneys' fees, incurred by the alleged infringer, by the copyright owner, or by the service provider. Do not use this process to remove criticism, a competitor's honest comparison, or a fair use quotation. We read notices carefully and we push back on ones that are transparently about something other than copyright.</p>

<h2>Fair use and quotation</h2>
<p>We quote others when it is useful to a reader, briefly, with attribution and with a link. That is ordinary journalism and we believe it is fair use. If you think a quotation of your work here exceeds that, write to us before filing anything formal. Nine times out of ten the answer is that we shorten it, credit it better, or remove it the same day.</p>

<h2>If you want to use our work</h2>
<p>Link to it freely; no permission is needed. Quote a paragraph with attribution and a link; also fine. For anything more, including republication, translation, classroom packets or commercial use, write to <a href="mailto:dmca@sableandsequin.com">dmca@sableandsequin.com</a> and say what you want to do. Requests that are reasonable usually get a yes.</p>
