<h1>Accessibility Statement</h1>
<p class="lede">Sable & Sequin is committed to making sableandsequin.com usable by as many people as possible, including readers who use screen readers, keyboard navigation, magnification, voice control or reduced-motion settings.</p>
<p class="stamp">Effective September 1, 2026. Reviewed against WCAG 2.1 Level AA.</p>

<h2>The standard we target</h2>
<p>We aim to conform to the Web Content Accessibility Guidelines 2.1 at Level AA, published by the World Wide Web Consortium. Those guidelines are the reference point used by the U.S. Department of Justice in interpreting the Americans with Disabilities Act as it applies to the web, and they are the yardstick we hold this site to.</p>

<h2>What we have actually done</h2>
<p>This is a specific list rather than a general assurance, because a general assurance is worth nothing.</p>
<ul>
  <li><strong>Semantic structure.</strong> Every page uses real landmarks &mdash; header, nav, main, aside, footer &mdash; one h1, and headings that descend in order without skipping a level, so a screen reader's outline matches the visible one.</li>
  <li><strong>A skip link</strong> is the first focusable element on every page and is visible when focused.</li>
  <li><strong>Keyboard operation.</strong> Everything on this site works from the keyboard. There is no JavaScript anywhere, so there are no custom widgets to trap focus. The menu, the disclosure sections and any filtering are built from native HTML controls.</li>
  <li><strong>Visible focus.</strong> A high-contrast focus ring is drawn on every interactive element using :focus-visible, and it is never removed.</li>
  <li><strong>Contrast.</strong> Body text is checked to at least 4.5:1 against its background and interface borders to at least 3:1, computed rather than estimated.</li>
  <li><strong>Text images.</strong> Every image carries descriptive alt text that says what is in it. Decorative artwork is drawn in the stylesheet or marked aria-hidden so it is not announced.</li>
  <li><strong>Resizing and reflow.</strong> Type is set in fluid units. The layout reflows to a single column and remains usable at 320 pixels wide and at 200 percent zoom, with no horizontal scrolling of the page body.</li>
  <li><strong>Tap targets.</strong> Interactive controls are at least 44 by 44 pixels.</li>
  <li><strong>Motion.</strong> There is no animation, no carousel, no auto-playing media and no scroll-triggered movement, and the small number of transitions are switched off under prefers-reduced-motion.</li>
  <li><strong>Language and titles.</strong> Every page declares its language and has a unique, descriptive title element.</li>
  <li><strong>Tables.</strong> Data tables use real table markup with header cells and scope attributes, and a caption where it helps.</li>
</ul>

<h2>Known limitations</h2>
<p>We would rather name these than have you discover them.</p>
<ul>
  <li><strong>Advertising.</strong> The advertisements in the reserved slots are supplied by third parties. We control the slot, its dimensions and its label; we do not control the markup inside it or its color contrast. This is the least accessible part of the site and we cannot fix it from here.</li>
  <li><strong>Wide tables.</strong> The size charts and comparison tables carry more columns than a narrow phone screen can show. They scroll horizontally inside their own container rather than shrinking to unreadable type. The container is keyboard-scrollable and labeled, but a wide table on a small screen remains harder work than we would like.</li>
  <li><strong>Photographic detail.</strong> Alt text describes what a photograph shows, but a written description cannot fully carry the exact shade or drape of a fabric. Where visual detail carries meaning, we also describe it in the body text.</li>
  <li><strong>PDF and third-party pages.</strong> Documents and websites we link to are outside our control and may not meet the same standard.</li>
</ul>

<h2>How this was assessed</h2>
<p>Assessment is by self-evaluation: automated checks of markup validity, heading order and image attributes; computed contrast ratios for every text and interface color pair in the palette; and manual keyboard-only walkthroughs of every page template at 360, 768, 1024 and 1440 pixels wide. We have not commissioned a third-party audit, and we are not going to imply that we have.</p>

<h2>Reporting a barrier</h2>
<p>If any part of this site stops you doing something, tell us. You do not need to know the technical term for the problem &mdash; "I cannot read the table on this page on my phone" is a perfectly good report.</p>
<p>Email <a href="mailto:access@sableandsequin.com">access@sableandsequin.com</a>, or write or call using the details below. Please include the page address, what you were trying to do, and the browser and assistive technology you were using if you know them.</p>

<h2>Our response commitment</h2>
<ul>
  <li>We acknowledge every accessibility report within <strong>two business days</strong>.</li>
  <li>We give an assessment and a plan, including a target date, within <strong>ten business days</strong>.</li>
  <li>Barriers that block access to content are treated as urgent and fixed as fast as we can, not queued behind feature work.</li>
  <li>If something cannot be fixed, we will say so honestly and offer the content another way &mdash; by email, in plain text, or read to you over the phone.</li>
</ul>

<h2>Formal complaints</h2>
<p>If our response does not resolve the problem, you may escalate to the owner of the site directly at <a href="mailto:hello@sableandsequin.com">hello@sableandsequin.com</a>. You also retain any rights you have under the Americans with Disabilities Act and under the law of your state; nothing on this page limits them.</p>

<h2>Continuing work</h2>
<p>Accessibility is not a box that gets checked once. Templates are re-tested when they change, new pages are checked before publication against the list above, and this statement is reviewed at least once a year or whenever the site's structure changes materially.</p>
