      <h2>Start with the timeline, not the price</h2>
      <p>The most expensive thing about alterations is leaving them late. A rush
      charge is 25 to 50 percent, and a shop that is full in May or December will
      simply say no, which is worse.</p>
      <div class="table-scroll">
      <table class="data">
        <caption>Working backward from the event. These are normal-season
        timings; add two weeks in April, May, November and December.</caption>
        <thead><tr><th scope="col">When</th><th scope="col">What happens</th></tr></thead>
        <tbody>
          <tr><th scope="row">8&ndash;10 weeks out</th><td>Buy the dress. Buy the shoes. Buy the shapewear.</td></tr>
          <tr><th scope="row">6 weeks out</th><td>First fitting, with the shoes and the underwear you will wear.</td></tr>
          <tr><th scope="row">3&ndash;4 weeks out</th><td>Second fitting. Most gowns need exactly two.</td></tr>
          <tr><th scope="row">2 weeks out</th><td>Collect. Hang it, do not fold it.</td></tr>
          <tr><th scope="row">1 week out</th><td>Wear it at home for an hour. Sit, walk stairs, raise your arms.</td></tr>
          <tr><th scope="row">Under 2 weeks</th><td>Possible at a rush charge, and only for simple work.</td></tr>
        </tbody>
      </table>
      </div>
      <p>The line that matters: <strong>bring the shoes and the underwear to
      every fitting.</strong> Both change your measurements, shapewear by up to
      an inch and a half, and a gown fitted without them will not fit on the
      night. This is the single most common reason a dress that was perfect in
      the shop is wrong at the event.</p>

