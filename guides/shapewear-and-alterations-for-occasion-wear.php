      </div>
      <p>Note the two cheapest items. A hem and repositioned cups together come
      to under $130 and change a dress more than another $300 of retail price
      would. That is the whole argument for buying less dress and altering it
      properly.</p>

      <h2>What shapewear does, and what it does not</h2>
      <p>Shapewear smooths. It compresses soft tissue slightly and it creates an
      even surface under a close-fitting fabric so that seams and edges do not
      print through. That is the entire mechanism and it is genuinely useful
      under satin, jersey and crepe.</p>
      <p>What it does not do is change your size. Marketing implies two sizes;
      the honest figure is between half an inch and an inch and a half at the
      waist depending on the garment and on you. Buying a gown a size down and
      planning to shapewear into it does not work and will make the evening
      miserable.</p>
      <h3>Choosing it</h3>
      <ul>
        <li><strong>Match the coverage to the dress.</strong> A high-waisted brief under a midi. A full slip under a column. Nothing under a heavily structured bodice, which already has boning doing the job.</li>
        <li><strong>Buy your actual size.</strong> Sizing down increases compression, creates a visible edge, and is the reason shapewear has a reputation for being unbearable.</li>
        <li><strong>Check the edges.</strong> Silicone-gripped or seamless edges do not print. A hard elastic band under a satin dress is visible from across a room.</li>
        <li><strong>Wear it to the fitting.</strong> Every time. This is not optional.</li>
        <li><strong>Try sitting.</strong> Almost all shapewear is comfortable standing. The test is twenty minutes in a chair.</li>
      </ul>
      <p>And an honest note: shapewear is optional. A well-altered dress in the
      right size over ordinary underwear looks better than a badly fitted dress
      over aggressive compression, every time. If you dislike wearing it, the
      answer is a better-fitting dress, not more of it.</p>

      <h2>Bras under occasion wear</h2>
      <p>Four situations and what solves each.</p>
      <dl>
        <dt>Strapless</dt><dd>A strapless bra fitted one band size down and one cup size up from your usual, which is how strapless sizing works. Or a bodice with built-in support, which a fitter can add for $60 to $140.</dd>
        <dt>Low back</dt><dd>A low-back converter strap, about $12, or a stick-on cup set. A long-line bra dyed to match is the old-school answer and still the best one.</dd>
        <dt>Deep V</dt><dd>A plunge bra or, more reliably, cups sewn into the dress. A fitter does this in one appointment.</dd>
        <dt>Sheer or beaded</dt><dd>Cups sewn in, nothing else. Anything with a band will be visible through the fabric under flash photography even when it is invisible in the room.</dd>
      </dl>

      <h2>Finding a good shop</h2>
      <p>Look for a rail of finished garments with paper tickets, a working
      industrial machine, and somebody who asks you to walk rather than only to
      stand. Ask what they charge to hem a lined gown; a shop that quotes one
      price regardless of the number of layers has not looked at your dress.</p>
      <p>Ask how many fittings they expect. Two is the right answer for a gown.
      One means they are confident and fast, which is sometimes true and often
      not. Three or more means the dress was too far from your size to begin
      with.</p>
      <p>And bring everything. Shoes, underwear, shapewear, the wrap, the jewelry
      if it affects the neckline. A fitter working with all of it will get the
      dress right the first time, and that is what you are paying for.</p>

