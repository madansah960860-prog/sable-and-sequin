      <p>The seated-dinner problem is real and is the most common Derby mistake.
      If the party has a sit-down component, anything over about six inches will
      have to come off, and a hat you have taken off is a hat you are carrying
      for four hours.</p>

      <h2>Fit and securing it</h2>
      <p>Hat sizing is the circumference of your head in inches, measured about
      a quarter inch above the ears and across the mid forehead. U.S. hat sizes
      run from roughly 21 inches, sold as small, to about 24, sold as extra
      large. Most women's occasion hats are sold in one size with an internal
      grosgrain band, which is adjustable with a strip of foam tape from any
      millinery supplier.</p>
      <p>Then secure it. A wide-brim hat outdoors in May in Kentucky or Tennessee
      will catch wind, and there is no recovering from chasing a hat across a
      lawn. Two hat pins through the crown into your hair, or a hidden elastic
      band, and the problem disappears. Do this before the event, not in the
      parking lot.</p>
      <p>Hair goes low: a chignon, a low bun or loose. A high style fights the
      crown and nothing about that contest ends well.</p>

      <h2>The dress</h2>
      <p>Knee to midi, in a print or a strong solid, in a fabric that will not
      crush across the lap during a two-hour drive. Cotton sateen, a linen blend,
      light silk or a good crepe. A sleeve or a strap rather than strapless,
      because the event is daytime and outdoors and you will be in the sun.</p>
      <p>Avoid: floor length, which reads as evening and drags on grass; heavy
      fabrics, which are unbearable in May in the South; and anything with a
      neckline that competes with the hat brim for attention. A high neck under a
      wide brim crowds the face.</p>

      <h2>Shoes, which matter more than the hat</h2>
      <p>This is the piece of advice that actually saves the day. A Derby party
      means six hours standing, much of it on grass or gravel, often with a walk
      from a distant parking area. The shoe decision is the difference between
      enjoying it and not.</p>
      <ul>
        <li><strong>Block heel, wedge or a smart flat.</strong> A stiletto sinks into turf and is unwearable.</li>
        <li><strong>Heel caps</strong> cost about $10 a pair and convert a heel you love into a heel that survives a lawn.</li>
        <li><strong>Broken in before the day.</strong> Two hours of wear at home in the week beforehand.</li>
        <li><strong>A flat in the car</strong> is not a failure. It is what everybody who has done this before is carrying.</li>
      </ul>

      <h2>Southern event conventions worth knowing</h2>
      <p>Some of these are regional enough that they genuinely surprise people
      moving to the South from elsewhere.</p>
      <ul>
        <li><strong>Daytime is dressier than you expect.</strong> A Southern daytime event asks for more than the equivalent event in the Midwest or the Northwest.</li>
        <li><strong>The white rule is about weddings, not about the calendar.</strong> The old prohibition on white after Labor Day has been dead for decades and nobody under sixty is applying it. Do not wear white to somebody's wedding; wear it whenever else you like.</li>
        <li><strong>Color is expected.</strong> At a Derby party in particular, an all-black outfit reads as though you have come from somewhere else and are passing through.</li>
        <li><strong>Bring a wrap.</strong> May evenings in Kentucky and Tennessee drop into the fifties, and outdoor events run late.</li>
        <li><strong>Mint juleps stain.</strong> So does bourbon, so does grass, and so does red clay. Dark hems and a stain pen in the bag.</li>
      </ul>

