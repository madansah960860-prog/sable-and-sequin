      <h2>The hat is the event</h2>
      <p>At a serious Derby party in the South, the hat is not an accessory that
      completes an outfit. It is the point, and the dress is chosen to work with
      it. That inversion catches out people dressing for their first one, who
      buy the dress and then look for a hat.</p>
      <p>Work in the other order. Choose the hat first, because the brim width
      determines the neckline, the earrings and the hair, and because the good
      ones sell out by early April.</p>

      <h2>Brim width, and the thing about tables</h2>
