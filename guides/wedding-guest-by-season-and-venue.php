      <p>The last row is the one nobody writes about. A dress you already own,
      with a different shoe, a different bag, and a $45 jacket or wrap, reads as
      a different outfit to every person in that room. Wedding season in America
      routinely involves three or four events in five months, and buying four
      dresses for that is how occasion wear becomes expensive.</p>

      <h2>A word about photographs</h2>
      <p>You will be photographed, and the photographs will outlive the event by
      decades. Two practical consequences. Very pale colors wash out under
      flash and very small prints go moir&eacute; and strange. And whatever you
      choose, choose something you can sit in, dance in and eat in, because the
      candid photographs are the ones that get kept.</p>

