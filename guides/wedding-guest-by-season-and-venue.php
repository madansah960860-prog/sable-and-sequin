      <h2>Three things that are true at every American wedding</h2>
      <p>Start here, because almost everything else is regional or situational
      and these three are not.</p>
      <ol>
        <li><strong>Do not wear white.</strong> This includes ivory, cream,
        champagne, and any blush pale enough to photograph white under a flash.
        The only exception is when the couple has explicitly asked guests to
        wear white, which happens and which will be stated clearly.</li>
        <li><strong>Dress for the venue, not the invitation alone.</strong> A
        barn in October and a hotel ballroom in October both say "cocktail" and
        mean different things. The venue tells you about footwear, fabric weight
        and whether there will be grass.</li>
        <li><strong>The ceremony is the formal part.</strong> If there is a
        religious ceremony, dress for that and not for the reception. Shoulders
        covered in a church or a temple is still the expectation in much of the
        country, and a wrap solves it in one object.</li>
      </ol>

      <h2>Twelve combinations</h2>
      <p>Venue down the side, season across. What each cell says is the length
      and the fabric weight, which between them settle most of the decision.</p>
      <div class="table-scroll">
      <table class="data">
