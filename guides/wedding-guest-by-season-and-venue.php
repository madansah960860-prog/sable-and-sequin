      <p>The pattern you should notice: the length barely moves and the fabric
      moves constantly. That is the actual mechanism of seasonal dressing in
      occasion wear and it is the opposite of how most guides present it.</p>

      <h2>Reading the invitation</h2>
      <p>The wording is a signal and so is the absence of wording. Here is what
      each version usually means in American use.</p>
      <dl>
        <dt>No dress code stated</dt><dd>Cocktail. This is the default and it is what the couple assumed you would infer.</dd>
        <dt>"Festive attire"</dt><dd>Cocktail with a color or a texture. Not a costume.</dd>
        <dt>"Garden party attire"</dt><dd>Daytime, outdoors, grass. Midi, print, block heel.</dd>
        <dt>"Cocktail attire"</dt><dd>Knee to midi, evening fabric, heel.</dd>
        <dt>"Black tie optional" or "formal"</dt><dd>Floor length, or midi in a formal fabric. About half the room does each.</dd>
        <dt>"Black tie"</dt><dd>Floor length. No ambiguity.</dd>
        <dt>"Beach formal"</dt><dd>Midi or floor in a light fabric, and a shoe you can carry.</dd>
        <dt>"Casual" or "come as you are"</dt><dd>Still a dress or good separates. It means no tie, not no effort.</dd>
      </dl>

      <h2>The regional adjustment</h2>
      <p>This is the part that guides written in New York get wrong about the
      rest of the country, and the part guides written anywhere get wrong about
      the South.</p>
      <p><strong>The South</strong> runs more formal at any stated code. A
      Nashville or Charleston cocktail wedding will have more floor-length
      dresses in the room than a Chicago one, and daytime events are dressier
      than their equivalents almost anywhere else in America.</p>
      <p><strong>The Mountain West and the Pacific Northwest</strong> run less
      formal, and outdoor venues are more common. Footwear matters more and
      fabric weight matters more, because the temperature drops thirty degrees
      after sunset.</p>
      <p><strong>The Midwest</strong> sits in the middle and is the most
      literal: if the invitation says cocktail, the room will be cocktail.</p>
      <p><strong>Texas and the Southwest</strong> run formal but hot. Summer
      weddings are frequently evening-only for that reason, and a fabric that
      breathes is worth more than one that photographs well.</p>

      <h2>Weather, honestly</h2>
      <p>The practical constraints people forget until the day.</p>
      <ul>
        <li><strong>Grass and heels.</strong> A stiletto sinks. A block heel, a wedge or a heel cap solves it for about $10. Outdoor ceremony means one of those, without exception.</li>
        <li><strong>Sun.</strong> A daytime outdoor wedding in July in the South is ninety minutes in direct sun in a dress you cannot change. Light colors, breathable fabric, and a hat if the code allows it.</li>
        <li><strong>The temperature drop.</strong> An evening outdoor reception loses twenty to thirty degrees after sunset in most of the country. A wrap is not an accessory, it is equipment.</li>
        <li><strong>Rain.</strong> Silk shows water spots permanently. Crepe, jersey and synthetics do not. For an outdoor wedding in a wet month, that decides the fabric on its own.</li>
      </ul>

