      <h2>Cost per wear, done properly</h2>
      <p>Occasion wear has the worst cost per wear in all of clothing, and the
      honest calculation is the one nobody publishes because it makes the
      category look bad.</p>
      <p>A $480 gown worn twice is $240 a wear. Add $70 of alterations and $45 of
      cleaning and it is $297 a wear. That is the real number for a very large
      proportion of the gowns bought in America every year, and any argument for
      buying has to beat it.</p>
      <p>A rental of the same gown at $95, twice, is $190 total and includes
      cleaning. So the honest headline is: <strong>for one or two wears, renting
      wins clearly.</strong> The interesting question is where the line is.</p>

      <h2>Where the line actually is</h2>
