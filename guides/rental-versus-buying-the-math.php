      <p>Break-even is around eight to ten wears of the same garment, which
      almost nobody reaches with a gown. On the arithmetic alone, renting wins
      for most people most of the time, and the reason people buy anyway is not
      economic.</p>

      <h2>The non-economic reasons to buy, which are legitimate</h2>
      <p>Money is not the only input and a guide that pretends otherwise is
      being obtuse.</p>
      <ul>
        <li><strong>Fit.</strong> A rental cannot be altered. If you are between sizes, long or short in the body, or have a fit issue that alterations solve, a bought and altered dress will fit in a way a rental will not.</li>
        <li><strong>Certainty.</strong> A rental arrives two days before the event. If it does not fit, your options are the backup size and nothing else. For a wedding you are in, that risk is not worth taking.</li>
        <li><strong>Timing.</strong> Rental depends on availability on your date. Popular sizes in popular styles go early in wedding season and in December.</li>
        <li><strong>Keeping it.</strong> Some events you want the dress from afterwards. That is a real value and it is fine to pay for it.</li>
      </ul>

      <h2>The hidden costs of each</h2>
      <h3>Buying</h3>
      <ul>
        <li>Alterations, $40 to $180 depending on the fabric and the work.</li>
        <li>Cleaning, $35 to $70 for a gown, more for beading, after every wear.</li>
        <li>Storage, which is space and a garment bag.</li>
        <li>The second-wear problem: the dress has to be re-wearable or the arithmetic above is what you get.</li>
      </ul>
      <h3>Renting</h3>
      <ul>
        <li>The damage waiver, $5 to $20, which covers minor stains and generally not structural damage.</li>
        <li>Late fees, $25 to $50 a day, which are easy to incur after a weekend event.</li>
        <li>No alterations, which for some bodies and some dresses is disqualifying.</li>
        <li>Availability risk on your date, which is the real one.</li>
      </ul>

      <h2>The two categories never to rent</h2>
      <p>First, <strong>anything you are wearing as part of a wedding party</strong>,
      including your own wedding. The risk profile is wrong: a shipping delay or
      a fit failure two days out is a disaster rather than an inconvenience, and
      you cannot alter the garment to fix it.</p>
      <p>Second, <strong>anything for an event with a long day and physical
      demands</strong> &mdash; a full Derby day, an outdoor summer wedding in the
      South, a gala you are hosting. Rentals cannot be altered for comfort, you
      will be in the garment for ten hours, and the damage waiver does not make
      grass stains on borrowed silk a relaxing thought.</p>

      <h2>Making rental work</h2>
      <ol>
        <li><strong>Book four to six weeks out</strong> for a popular date. Availability, not price, is the constraint.</li>
        <li><strong>Always take the backup size.</strong> It is usually free and it is the entire risk mitigation.</li>
        <li><strong>Choose a forgiving silhouette.</strong> A wrap, an A-line or anything with a tie works across a size. A fitted column does not.</li>
        <li><strong>Read the return timing.</strong> Most services want it back the first business day after the rental period, which after a Saturday event means Monday.</li>
        <li><strong>Photograph it on arrival</strong>, including any existing marks. Two minutes, and it settles any dispute.</li>
        <li><strong>Take the damage waiver.</strong> At $5 to $20 against a $400 replacement value it is straightforwardly good value for an evening involving red wine.</li>
      </ol>

      <h2>The third option nobody mentions</h2>
      <p>Buy secondhand. Occasion wear is the ideal secondhand category: worn
      once or twice, stored carefully, and sold at forty to sixty percent of
      retail by somebody with exactly your problem. A $480 gown at $180
      secondhand, plus $60 of alterations, is $240 and you keep it, which beats
      both columns of the table above.</p>
      <p>The constraints are real: you need time, you need to be able to try it
      on or to buy where returns are accepted, and you need your measurements.
      But for anybody planning six weeks ahead rather than nine days, this is
      frequently the best answer available and it almost never appears in
      articles about this subject.</p>

