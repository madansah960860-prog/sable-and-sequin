      <h2>The two correct answers, costed</h2>
      <h3>Answer one: a floor-length gown</h3>
      <p>The straightforward reading. A column, an A-line or a fit-and-flare in a
      formal fabric, hemmed half an inch off the floor in the shoes you will
      wear. Buy band $180 to $600 at U.S. retail before tax; rental band $50 to
      $140. Budget $40 to $90 for a hem and a take-in on top of a purchase.</p>
      <p>Advantages: unambiguously correct, photographs well, and if you buy
      black or navy it will come out again. Disadvantages: the cost per wear is
      poor unless it does come out again, and a floor-length gown is genuinely
      difficult to move in if it is not fitted properly.</p>
      <h3>Answer two: a midi in a formal fabric</h3>
      <p>The more useful buy for most people. A midi or ankle-length dress in
      silk crepe, velvet or heavy satin, with an evening shoe, an evening bag and
      real or good jewelry. Buy band $140 to $420; rental band $45 to $110.</p>
      <p>Advantages: much easier to re-wear, easier to move in, cheaper to alter,
      and works at every code from cocktail upward. Disadvantages: it requires
      you to get the fabric right, and a midi in the wrong cloth is the most
      common way to be underdressed at one of these.</p>

      <h2>The accessories that move the needle</h2>
      <p>At this code, accessories carry more signal than they do anywhere else,
      because they are how a midi becomes formal.</p>
      <ul>
        <li><strong>The bag.</strong> A clutch or a small box bag. Bringing a tote to a black tie optional event is the single most common error in the room and it undoes an otherwise correct outfit instantly.</li>
        <li><strong>The shoe.</strong> An evening shoe means a heel or a flat in satin, metallic leather or patent. A daytime leather pump in a neutral color reads as work, whatever the dress is doing.</li>
        <li><strong>Jewelry.</strong> Either a statement earring or a statement necklace, not both. This is a convention rather than a rule and it is nearly universal in practice.</li>
        <li><strong>The wrap.</strong> An evening venue will be cold. A velvet or silk wrap is part of the outfit; a wool coat over a gown is fine to arrive in and should be checked.</li>
      </ul>

      <h2>What gets you side-eyed</h2>
      <p>Not much, honestly, and that is worth saying because the anxiety around
      this code is out of proportion to the risk. Four things genuinely read as
      wrong:</p>
      <ol>
        <li>A short cotton dress, which reads as daytime at an evening event.</li>
        <li>Day shoes, which is a bigger signal than most people realize.</li>
        <li>A tote bag or a work bag.</li>
        <li>White, at a wedding.</li>
      </ol>
      <p>Everything else is within range. A woman in a well-fitted navy midi with
      good shoes is not underdressed next to a woman in a gown, and anybody who
      thinks otherwise is not somebody whose opinion should govern your evening.</p>

      <h2>If you genuinely cannot decide</h2>
      <p>Two tie-breakers. First, the venue: a hotel ballroom, a museum or a
      country club pulls toward floor length; a restaurant, a brewery or a home
      pulls toward a midi. Second, the start time: an event starting at 6:30 PM
      or later is more formal than one starting at 4:00 PM at the same stated
      code.</p>
      <p>And if it is still close, ask the host. It is a normal question, it is
      not gauche, and hosts would overwhelmingly rather answer it than have a
      guest be uncomfortable all evening.</p>

