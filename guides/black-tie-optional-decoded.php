      <h2>What the host is actually saying</h2>
      <p>"Black tie optional" is a piece of American hospitality doing two jobs
      at once. The host would like the room to look formal. The host also does
      not want to require a guest to rent a tuxedo, which is a real cost and a
      real barrier.</p>
      <p>So it is not a lower dress code than black tie. It is black tie with
      permission to be slightly less. Read it as "formal, and we will not turn
      you away without floor length," because that is how it functions.</p>
      <p>The practical consequence for women is that there are two correct
      answers, and both of them show up in the room in roughly equal numbers. A
      floor-length gown is correct. A midi or ankle-length dress in a genuinely
      formal fabric, with evening shoes and evening jewelry, is also correct.
      Neither is a compromise.</p>

      <h2>Fabric is doing the work, not length</h2>
      <p>This is the single most useful idea on this page. People treat hemline
      as the whole signal and it is the smaller half of it.</p>
      <p>Consider two dresses of exactly the same length, both hitting the ankle.
      One is cotton poplin with a small floral print. One is silk crepe in
      midnight blue. The first is a garden party dress and would be visibly wrong
      at a black tie optional gala. The second is entirely correct. The length is
      identical; the fabric decided it.</p>
