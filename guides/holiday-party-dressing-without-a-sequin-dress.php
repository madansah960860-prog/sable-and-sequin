      <h2>The sequin tax</h2>
      <p>Every December, American retail fills with sequined minidresses at
      $120 to $300, and every January they go to the back of a closet and stay
      there. The garment is not the problem; the arithmetic is. A dress that can
      only be worn in the four weeks between Thanksgiving and New Year, and that
      is memorable enough to be noticed twice, has a realistic lifetime of two
      wears.</p>
      <p>At $180 that is $90 a wear, which is worse than renting and much worse
      than the alternatives below. None of this is an argument against sequins.
      It is an argument against buying an occasion piece that can only answer one
      occasion.</p>

      <h2>Six alternatives that read as festive</h2>
      <h3>1. Velvet, in any color</h3>
      <p>The most effective single substitution. Velvet reads as evening and as
      seasonal without being a costume, photographs beautifully in low light, and
      a velvet midi or blazer comes out again in February and at any black tie
      optional event. Band $110 to $280.</p>
      <h3>2. Satin in a strong color</h3>
      <p>A bias-cut satin slip dress in emerald, burgundy, sapphire or bronze
      does the whole job of a sequin dress with a fraction of the specificity. It
      also works at a summer wedding, which a sequin dress does not. Band $90 to
      $240.</p>
      <h3>3. Metallic thread rather than metallic surface</h3>
      <p>A lurex knit, a brocade, or a jacquard with a metal thread running
      through it catches light without covering you in it. Reads as expensive,
      does not read as December. Band $120 to $300.</p>
      <h3>4. A tuxedo-style separate</h3>
      <p>A well-cut black or midnight blazer with satin lapels over a silk
      camisole and tailored pants. The most re-wearable option on this list by a
      wide margin, and the one most likely to become a permanent part of a
      wardrobe. Band $180 to $420 for the jacket, which carries the outfit.</p>
      <h3>5. One shining accessory on a plain dress</h3>
      <p>A plain black crepe midi you already own, plus a beaded clutch, a
      crystal earring or a metallic shoe. Total added cost $45 to $140, and the
      dress stays useful.</p>
      <h3>6. Color instead of shine</h3>
      <p>A saturated red, a deep green or a true fuchsia in a matte fabric reads
      as festive on its own. It also photographs better than shine does under the
      mixed lighting of most party venues. Band $90 to $260.</p>

