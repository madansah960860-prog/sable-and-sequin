      <p>Notice that renting the sequin dress still beats buying it. If you want
      the sequin dress &mdash; and it is a perfectly good thing to want &mdash;
      renting is the rational way to have it.</p>

      <h2>Office parties are a different problem</h2>
      <p>An office holiday party is a work event in party clothes, and the
      calculation changes because the people in the room will see you again on
      Monday morning.</p>
      <p>The workable rule: one level up from your normal office dress, and no
      more. If you wear business casual, a velvet blazer over what you would
      normally wear is exactly right. A floor-length gown at an office party
      makes everybody else feel underdressed, which is a social cost you carry
      afterwards.</p>
      <p>Two specifics. Whatever it is, you should be able to sit in it at a
      table for two hours, because that is what an office party is. And avoid
      anything that requires managing &mdash; a strapless neckline, a high slit,
      a hem you have to hold &mdash; because you will be talking to your director
      while managing it.</p>

      <h2>Getting two wears a year out of an occasion piece</h2>
      <p>The whole economics of this category depends on the second wear. Three
      properties make it likely.</p>
      <ul>
        <li><strong>Unmemorable color.</strong> Black, navy, deep green and burgundy can reappear in four months. Pale blue with a distinctive neckline cannot.</li>
        <li><strong>Silhouette that changes with a shoe.</strong> A column that reads formal with a heel and relaxed with a flat and a jacket is two outfits.</li>
        <li><strong>Cleanable.</strong> A dress that costs $45 to clean and cannot be worn again until it is, is a dress you will not reach for. Check the care label before you buy, not after.</li>
      </ul>
      <p>And the practical move: photograph what you wore to which event. Not for
      vanity &mdash; so that in eighteen months you know whether the people at
      this party saw this dress at that one. Nobody remembers. The photograph
      does.</p>

