    <div class="room__head">
      <p class="room__label">The decoder</p>
      <h2>Six codes, in order of formality</h2>
    </div>
    <p class="lede">Choose a stop on the line. It lights the entry below. Every
    code gets the same five answers: what it means, what to wear, what length,
    what gets you side-eyed, and where you will actually meet it.</p>
    <ol class="ruler">
      <li><a href="#code-garden"><span class="ruler__n">1</span>Garden party</a></li>
      <li><a href="#code-derby"><span class="ruler__n">2</span>Derby and race day</a></li>
      <li><a href="#code-festive"><span class="ruler__n">3</span>Festive</a></li>
      <li><a href="#code-cocktail"><span class="ruler__n">4</span>Cocktail</a></li>
      <li><a href="#code-bto"><span class="ruler__n">5</span>Black tie optional</a></li>
      <li><a href="#code-blacktie"><span class="ruler__n">6</span>Black tie</a></li>
    </ol>
    <p class="ruler__ends"><span>Least formal</span><span>Most formal</span></p>
    <div class="decoder">
      <article class="code" id="code-garden">
        <h3>Garden party</h3>
        <p class="code__rank">Formality 1 of 6</p>
        <dl>
          <dt>What it means</dt><dd>Daytime, outdoors, on grass. The least formal code that still asks you to dress. Common for spring showers, rehearsal brunches and Southern daytime weddings.</dd>
          <dt>What to wear</dt><dd>A midi or tea-length dress in a light fabric, a floral or a solid pastel, a block heel or a smart flat, a light jacket you can carry.</dd>
          <dt>Length</dt><dd>Midi to tea length, 27&ndash;36 in from the natural waist</dd>
          <dt>What gets you side-eyed</dt><dd>Stilettos on grass. Anything strapless if it is before noon. A cocktail dress in a heavy fabric, which reads as evening in daylight.</dd>
          <dt>Where you will see it</dt><dd>Spring showers, daytime weddings, garden club events, Easter</dd>
        </dl>
      </article>
      <article class="code" id="code-derby">
        <h3>Derby and race day</h3>
        <p class="code__rank">Formality 2 of 6</p>
        <dl>
          <dt>What it means</dt><dd>A Southern institution with its own conventions. Daytime, outdoors, and the hat is not optional at a serious party. The dress is a supporting player.</dd>
          <dt>What to wear</dt><dd>A knee-length or midi dress in a print, a hat or fascinator, and shoes you can stand in for six hours on uneven ground.</dd>
          <dt>Length</dt><dd>Knee to midi, 24&ndash;32 in from the natural waist</dd>
          <dt>What gets you side-eyed</dt><dd>A brim so wide your table neighbors cannot see. Wedges with a formal dress. Anything white if it is a wedding-adjacent event.</dd>
          <dt>Where you will see it</dt><dd>Kentucky Derby parties, Steeplechase, Iroquois, spring race meets</dd>
        </dl>
      </article>
      <article class="code" id="code-festive">
        <h3>Festive</h3>
        <p class="code__rank">Formality 3 of 6</p>
        <dl>
          <dt>What it means</dt><dd>December shorthand for “have fun with it.” The least defined code in American use and the one that causes the most anxiety, because it means different things at an office party and at a friend's house.</dd>
          <dt>What to wear</dt><dd>Cocktail-length or a dressed-up separate. Velvet, satin, metallic thread, a strong color. One shining element, not four.</dd>
          <dt>Length</dt><dd>Knee to midi, or elevated separates</dd>
          <dt>What gets you side-eyed</dt><dd>A literal holiday sweater at a company party where the invitation said festive rather than ugly-sweater. Head-to-toe sequins at a family dinner.</dd>
          <dt>Where you will see it</dt><dd>Office holiday parties, December dinners, New Year's Eve at home</dd>
        </dl>
      </article>
      <article class="code" id="code-cocktail">
        <h3>Cocktail</h3>
        <p class="code__rank">Formality 4 of 6</p>
        <dl>
          <dt>What it means</dt><dd>The workhorse of American occasion dressing. Evening, indoors, formal enough to need a dress and relaxed enough not to need a gown.</dd>
          <dt>What to wear</dt><dd>A knee-length or midi dress, or a very well-cut jumpsuit. A heel. A small bag. Real jewelry or good costume, not both.</dd>
          <dt>Length</dt><dd>Knee to midi, 23&ndash;34 in from the natural waist</dd>
          <dt>What gets you side-eyed</dt><dd>Floor length, which overshoots. A daytime print in a daytime fabric. Anything you would wear to work without changing a single thing.</dd>
          <dt>Where you will see it</dt><dd>Most evening weddings, rehearsal dinners, benefits, awards dinners</dd>
        </dl>
      </article>
      <article class="code" id="code-bto">
        <h3>Black tie optional</h3>
        <p class="code__rank">Formality 5 of 6</p>
        <dl>
          <dt>What it means</dt><dd>The host would like the room to look formal and does not want to require a tuxedo. In practice about half the room wears floor length and half wears a long cocktail dress, and both are correct.</dd>
          <dt>What to wear</dt><dd>A floor-length gown, or a midi in a formal fabric with evening jewelry and an evening shoe. The fabric does more work than the length here.</dd>
          <dt>Length</dt><dd>Midi to floor, 34&ndash;60 in from the natural waist</dd>
          <dt>What gets you side-eyed</dt><dd>A short cotton dress. Day shoes. Treating the word optional as permission to wear what you wore to the office.</dd>
          <dt>Where you will see it</dt><dd>Larger weddings, galas, benefit dinners, milestone anniversaries</dd>
        </dl>
      </article>
      <article class="code" id="code-blacktie">
        <h3>Black tie</h3>
        <p class="code__rank">Formality 6 of 6</p>
        <dl>
          <dt>What it means</dt><dd>The most formal code most Americans will ever be invited to. Evening, after six, floor length. There is no ambiguity in it and that is the point.</dd>
          <dt>What to wear</dt><dd>A floor-length gown. A formal fabric: silk, velvet, crepe, heavy satin, beading. Evening shoes, an evening bag, and either earrings or a necklace.</dd>
          <dt>Length</dt><dd>Floor length, hemmed to the shoe you will actually wear</dd>
          <dt>What gets you side-eyed</dt><dd>Anything above the ankle. A day fabric such as cotton or linen. A tote bag, which is the single most common mistake in the room.</dd>
          <dt>Where you will see it</dt><dd>Galas, formal weddings, opera openings, some New Year's Eve events</dd>
        </dl>
      </article>
    </div>
    <p class="small muted">Codes are conventions, not rules, and they vary
    regionally. Nashville and Charleston run more formal than Chicago at the
    same stated code; a Friday wedding runs less formal than a Saturday one.
    When the invitation is genuinely ambiguous, ask the host. Nobody has ever
    been annoyed by that question.</p>
  </div>
</section>

