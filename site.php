<section class="room">
  <div class="wrap">
    <div class="room__head">
      <p class="room__label">Method</p>
      <h2>Why a decoder and not a lookbook</h2>
    </div>
    <div class="cols-2">
      <div>
        <p>Occasion dressing is the one part of a wardrobe where people
        genuinely do not know the rules, and where getting it wrong is
        uncomfortable in a way that getting a weekday outfit wrong is not. You
        can be underdressed at a gala in a way you cannot really be underdressed
        at a grocery store, and everybody in the room notices.</p>
        <p>The anxiety is not about taste. It is about information. An
        invitation says "black tie optional" and gives you no way to find out
        what that means in this town, at this venue, in this month. So the site
        answers that first and talks about dresses second.</p>
        <p>A lookbook cannot do that job, because you cannot buy the look. There
        is one of that dress, it is a size 6, and the event is in nine days.
        What transfers between events is the code, the length, the fabric and
        the shoe, and those are learnable.</p>
      </div>
      <div>
        <p>The second thing this site does is money. Occasion wear has the worst
        cost per wear in clothing: a gown worn twice at $480 is $240 a wear,
        which is not a sensible number and which nobody says out loud. So every
        guide here gives price bands in dollars before sales tax, and one of
        them is entirely about
        <a href="guides/rental-versus-buying-the-math.php">whether to rent
        instead</a>.</p>
        <p>And the third is alterations, because almost every gown needs them.
        A $180 dress with $60 of work fits better than a $600 one off the rack,
        and the timeline for getting that work done before an event is longer
        than people expect. That guide exists too.</p>
        <p>How the research is done, and how corrections get made, is in the
        <a href="policies/editorial-policy.php">Editorial Policy</a>.</p>
      </div>
    </div>
